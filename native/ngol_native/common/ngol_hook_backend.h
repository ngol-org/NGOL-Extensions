#pragma once

// フック機構のバックエンド境界。
//
// 命令の書き換えとトランポリン生成は CPU 命令セットと OS に依存するため、
// そこだけを差し替えられるようにこの 1 枚に閉じてある。common/ 側は
// 「どのライブラリで実現しているか」を知らない。
//
// 型は windows.h に依存させない。ここが依存すると、境界を分けた意味が無くなる。
//
// ------------------------------------------------------------
// この DLL の方針（common/ と backend-*/ の両方に適用）
// ------------------------------------------------------------
//
// P1. 実行時に確保しない。
//     置き場はすべて固定長。malloc / HeapAlloc / new を使わない。
//
// P2. 実行時に常駐しない。
//     スレッド・タイマー・周期処理を持たない。動くのは呼ばれたときだけ。
//
// P3. 置き場が要る機能は、呼ぶ側が確保して渡す。この DLL は預かるだけ。
//
// P4. 既に公開した口のシグネチャを変えない。欄を足すときは新しい口にする。
//     引数を増やすと、先に配られた版の呼び出し側が壊れる（C ABI の破壊的変更）。
//
// なぜ: フックは確保・同期・スレッド生成の関数にも張られる。ここが確保すると、
// その関数に張った瞬間に自分を呼び戻す。常駐すると、フックを 1 つも張らない
// ホストにも負担を課す。
//
// ------------------------------------------------------------
// バックエンドが満たすべき条件
// ------------------------------------------------------------
//
// detour は jmp で入ること。呼び出し元のフレームを消費しないこと。
//
// common/ は「フック本体の入口で [rsp] が呼び出し元の戻り番地である」ことに
// 依存している（第 5 引数以降の取得が既にこの前提に立っている）。
// call で包む方式・例外を使う方式は、この前提を満たさない。
//
// 満たさない場合、静かに壊れる。もっともらしいポインタが返るだけで
// エラーにはならない。
//
// 戻り値の規約: エラー文字列を返し、成功時は nullptr。
// 返す文字列は静的な寿命を持つこと（呼び出し側は保持だけして解放しない）。

extern "C" {

/// バックエンドを初期化する。複数回呼ばれてよい。
const char* NgolBackend_Init(void);

/// target に detour を割り当て、原関数を呼ぶための入口を trampoline へ返す。
/// この時点ではまだ有効化しない。
const char* NgolBackend_Create(void* target, void* detour, void** trampoline);

/// Create したフックを有効化する。
const char* NgolBackend_Enable(void* target);

/// 有効化を解除する。解除できない状態でも呼び出し側は続行するため戻り値は返さない。
void NgolBackend_Disable(void* target);

/// フックの登録自体を取り除く。
void NgolBackend_Remove(void* target);

/// バックエンドを終了する。プロセス終了時のみ呼ぶ。
void NgolBackend_Shutdown(void);

/// 診断用の実装名。どのバックエンドで動いているかを外から確認できるようにする。
const char* NgolBackend_Name(void);

} // extern "C"
